const { load, specs } = require('../lib/bugfix-fixtures.js');
const fs = require('node:fs');
const path = require('node:path');
const BY_NAME = new Map(specs(path.resolve(__dirname, '..')).map((f) => [f.name, f]));

// Any string that looks like a repo-relative path with an extension -
// "src/flask/app.py", "packages/shared/src/looseEqual.ts". Requires a slash
// so ordinary prose ("fix the run() method") doesn't get treated as a
// citation - that's what the function-name check below is for instead.
const PATHLIKE = /\b((?:[\w.-]+\/)+[\w.-]+\.[A-Za-z]{1,6})\b/g;

// A bare filename with no directory - "app.py", "tree.go". The character
// class already includes the dot, so a greedy match swallows a whole
// underscore-joined token like "test_app.py" in one go rather than stopping
// at "app.py" - `\b` only fires where \w meets non-\w, and "_" is \w, so
// there is no boundary between "test_" and "app.py" to split on.
const FILENAME = /\b[\w.-]+\.[A-Za-z]{1,6}\b/g;

function escapeRegExp(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

// Whole path/filename tokens mentioned in prose, matched as complete tokens -
// never substring containment, which is what let "test_app.py" satisfy a
// check meant for "app.py" purely because one string's characters contain
// the other's.
function fileTokens(text) {
  const toks = new Set();
  for (const [t] of text.matchAll(PATHLIKE)) toks.add(t);
  for (const [t] of text.matchAll(FILENAME)) toks.add(t);
  return toks;
}

// True when some whole token in `text` names `sf` - either the exact
// repo-relative path, or a basename match (bare filename, or a differently
// -rooted path ending in the same basename). Never a substring check.
function citesFile(tokens, sf) {
  const base = path.basename(sf);
  for (const tok of tokens) {
    if (tok === sf || tok === base || path.basename(tok) === base) return true;
  }
  return false;
}

// A truncated stub and a correctly-argued decline both compute out to
// "invented nothing" / "proposed no diff" against the graders below - so an
// empty (or whitespace-only) answer has to be rejected before either grader
// runs, or the not-a-bug control can't tell them apart. Not a length
// threshold standing in for quality (see evals/AGENTS.md on magic numbers) -
// a bright line on literal absence of content, nothing more.
function hasSubstance(output) {
  return String(output).trim().length > 0;
}
const NO_SUBSTANCE = { pass: false, score: 0, reason: 'Empty or whitespace-only output - nothing to grade.' };

// A unified-diff file header. `--- a/route.go` is diff syntax describing the
// model's OWN patch, not a citation of the tree, and `a/`/`b/` are the
// prefixes `git diff` puts there.
const DIFF_HEADER = /^(?:---|\+\+\+|diff --git)\s/;

// Generated bytecode: no source tree carries __pycache__/*.pyc, so resolving
// one against the tree can only ever come out false, whatever the answer said.
const GENERATED = /(^|\/)__pycache__\//;

// True when the next non-blank line after `pos` opens a fenced code block -
// i.e. the path just matched was the filename heading the content that
// follows. Cheap structural read of markdown, no prose matching.
function headsCodeBlock(text, pos) {
  for (const line of text.slice(pos).split('\n').slice(1)) {
    if (!line.trim()) continue;
    return /^\s*```/.test(line);
  }
  return false;
}

// Claim: a theory grounded in the real code cites real files. A path that
// does not exist in the tree the model was actually given is either
// fabricated from training-data memory of a *different* version of the
// project, or copied from elsewhere in the prompt (a traceback frame through
// a dependency, e.g.) rather than the repo under investigation - the latter
// is legitimate, so anything that appears verbatim in the issue text the
// model was given is exempted rather than flagged.
//
// Four kinds of token are not citations of existing code at all, and flagging
// them scored the same artifact in both directions:
//   - a unified-diff header, which is the answer's own patch. 6 of the 10
//     flags in results/fix-bug@1.0.1.json were `--- a/x`/`+++ b/x` pairs for
//     files that DO exist under their real names, while `proportionate_fix`
//     and `regression_proof` (+0.49) both pay for producing that patch;
//   - a filename heading a code block the answer supplies: a file it proposes
//     to CREATE. develop-feature cut its own noInventedCitations over exactly
//     this - 6 of its 9 flags were files the plan proposed to create - and
//     here it hit a row scoring regression_proof=1 for the regression test it
//     was flagged for offering;
//   - a URL, whose host and path PATHLIKE reads as a repo-relative path;
//   - a generated artifact under __pycache__/, which is never in a tree.
// Left flagged, deliberately: a path quoted from the issue body (already
// exempt - it is a claim about the reporter's environment, not this repo) and
// a real-but-wrong path, e.g. a monorepo path missing its `packages/` root.
function noInventedFileRefs(output, context) {
  if (!hasSubstance(output)) return NO_SUBSTANCE;
  const spec = BY_NAME.get(context?.vars?.fixture);
  if (!spec) return { pass: true, score: 1, reason: 'No fixture: nothing to resolve file references against.' };
  const { dir } = load(spec);
  const issueBody = String(context?.vars?.issueBody || '');
  const bad = [];
  let checked = 0;
  // Blank each URL out in place: same length, so every offset below still
  // points where it did.
  const scan = String(output).replace(/\bhttps?:\/\/\S+/g, (m) => ' '.repeat(m.length));
  for (const m of scan.matchAll(PATHLIKE)) {
    const p = m[1];
    const lineStart = scan.lastIndexOf('\n', m.index) + 1;
    const nl = scan.indexOf('\n', m.index);
    const lineEnd = nl < 0 ? scan.length : nl;
    if (DIFF_HEADER.test(scan.slice(lineStart, lineEnd))) continue;
    checked += 1;
    if (fs.existsSync(path.join(dir, p))) continue;
    if (issueBody.includes(p)) continue; // quoted from the report, not claimed as this repo's code
    if (GENERATED.test(p)) continue;
    if (headsCodeBlock(scan, lineEnd)) continue; // a file the answer proposes to create
    bad.push(p);
  }
  if (!bad.length) {
    return {
      pass: true,
      score: 1,
      reason: checked ? `All ${checked} file reference(s) resolve to the tree or the report.` : 'No file path cited.',
    };
  }
  return { pass: false, score: 0, reason: `References to files not in the tree and not in the report: ${[...new Set(bad)].slice(0, 4).join(', ')}.` };
}

// Claim: did the answer land where the real fix landed? Computed against the
// withheld fix's file/function list, never against wording in the model's
// output - see the shared fixtures.js sibling for the same principle applied
// to a review's citations. For the "not a bug" control there is no real fix
// to match against; the question inverts to whether the model invented one.
//
// Recall alone. It shipped as `touches_real_fix` = recall x precision over
// every real in-tree file named, and that product reported the opposite sign
// from both its halves - -0.233 for the skill arm on recall of +0.111 - which
// was twice read out as "the skill is worse at finding where the bug is".
// Measured over the 105 non-control rows of results/fix-bug@1.0.1.json, the
// precision half was mostly counting TEST files: the skill arm named 94 real
// files to the baseline's 54 and 35 of the 40 extra were the file a
// regression test goes in, so the term docked the arm for the behaviour
// `regression_proof` scores +0.49 for (worst case: both flask-6096 files
// named plus both test files, 2/4, a full-recall answer halved). Excluding
// test files from the denominator it goes flat on those same rows, 0.937 vs
// 0.923, against 0.909 vs 0.612 as shipped. And the scattergun it was built to
// catch never happens - the most real files any of the 105 answers names is
// 4. A denominator of files named AS THE PLACE TO CHANGE would be the honest
// version; nothing deterministic separates that from "I read this file"
// without prose-matching, the wall develop-feature's `noInventedCitations`
// hit. Unified-diff headers dodge the prose rule but not the artifact: 12-13
// rows carry one and it is usually the test file.
function findsTheFix(output, context) {
  if (!hasSubstance(output)) return NO_SUBSTANCE;
  const spec = BY_NAME.get(context?.vars?.fixture);
  if (!spec) return { pass: true, score: 1, reason: 'No fixture: nothing to resolve against.' };
  const f = load(spec);
  const text = String(output);

  if (!f.fix) {
    // A fenced diff/patch block, or raw unified-diff hunk markers, proposing
    // an edit. Detecting the syntax, not the prose around it.
    const proposesEdit = /```(?:diff|patch)\b[\s\S]*?```/i.test(text) || /^--- [ab]\//m.test(text) || /^@@ -\d+/m.test(text);
    if (!proposesEdit) {
      return { pass: true, score: 1, reason: 'No diff/patch proposed against the source - correctly treated as not a defect in this codebase.' };
    }
    return { pass: false, score: 0, reason: 'Output includes a diff/patch changing the source tree for a report that has no real fix.' };
  }

  const tokens = fileTokens(text);
  const fileHits = f.sourceFiles.filter((sf) => citesFile(tokens, sf));
  const funcHits = (f.functions || []).filter((fn) => new RegExp(`\\b${escapeRegExp(fn)}\\b`).test(text));
  const total = f.sourceFiles.length + (f.functions || []).length;
  const score = total ? (fileHits.length + funcHits.length) / total : fileHits.length ? 1 : 0;
  // Threshold: naming a file the fix changed. A function name alone still
  // scores partial credit, but "found where the bug lives" is a claim about
  // the file - the same symbol can be reached from several.
  const pass = fileHits.length > 0;

  const reason = pass
    ? `Named ${fileHits.length}/${f.sourceFiles.length} real file(s)${funcHits.length ? ` and ${funcHits.length}/${(f.functions || []).length} real function(s)` : ''}.`
    : `Did not name any of the real fix's file(s): ${f.sourceFiles.join(', ')}.`;
  return { pass, score, reason };
}

module.exports = { noInventedFileRefs, findsTheFix, PATHLIKE, FILENAME, fileTokens, citesFile, hasSubstance, headsCodeBlock };
